"""Dynamical Lie algebra (DLA) of a layered circuit.

Generators are the Hermitian operators G with gates exp(-i theta G / 2); the DLA is the real Lie
closure of {i G} under commutators. Two cases need care:

* Tied parameters. CRX(a) has the single generator (I - Z_c) X_t / 2, a *sum* of two Pauli
  strings. Its closure can be smaller than that of the two strings taken separately.
* Fixed gates. With CNOT or CZ entanglers a layer is E R(theta), where E is a fixed Clifford.
  Rewriting U = E R_L ... E R_1 as a product of rotations about E^k G E^-k shows that, at large
  depth, the reachable set is generated by the orbit of every generator under conjugation by E.

``lie_algebra_dimension`` returns the infinite-depth (architecture-level) dimension.
"""

from __future__ import annotations

import numpy as np

from . import pauli as pl
from .circuits import Circuit, Clifford

Op = dict[pl.Pauli, float]  # Hermitian operator in the Pauli basis


def _conjugate_op(g: Op, cliffords: list[Clifford], n: int) -> Op:
    """E g E^dag with E = (last clifford) ... (first clifford)."""
    out = dict(g)
    for c in cliffords:  # E g E^dag = G_m ... G_1 g G_1 ... G_m : innermost (first gate) first
        nxt: Op = {}
        for p, coef in out.items():
            k, r = pl.conjugate(p, c.gate, n, c.control, c.target)
            sign = 1.0 if k == 0 else -1.0
            nxt[r] = nxt.get(r, 0.0) + sign * coef
        out = {p: v for p, v in nxt.items() if abs(v) > 1e-12}
    return out


def _key(g: Op) -> tuple:
    return tuple(sorted((p, round(v, 12)) for p, v in g.items()))


def layer_generators(circuit: Circuit) -> list[Op]:
    """Distinct generators of the circuit, closed under conjugation by the fixed layer Clifford."""
    n = circuit.n_qubits
    gens: dict[tuple, Op] = {}
    for g in circuit.generators.values():
        gens.setdefault(_key(g), g)
    n_layers = max(circuit.spec.n_layers, 1)
    cliffords = [op for op in circuit.ops if isinstance(op, Clifford)]
    per_layer = cliffords[: len(cliffords) // n_layers] if cliffords else []
    if per_layer:
        frontier = list(gens.values())
        while frontier:
            nxt = []
            for g in frontier:
                h = _conjugate_op(g, per_layer, n)
                if _key(h) not in gens and _key({p: -v for p, v in h.items()}) not in gens:
                    gens[_key(h)] = h
                    nxt.append(h)
            frontier = nxt
    return list(gens.values())


def _bracket(a: Op, b: Op) -> Op:
    """i[A, B] in the Pauli basis."""
    out: Op = {}
    for p, ca in a.items():
        for q, cb in b.items():
            if pl.commutes(p, q):
                continue
            k, r = pl.product(p, q)  # PQ = i^k R, k odd;  i[P,Q] = 2 i^(k+1) R
            out[r] = out.get(r, 0.0) + 2.0 * ca * cb * (-1.0 if k == 1 else 1.0)
    return {p: v for p, v in out.items() if abs(v) > 1e-12}


def _closure_strings(strings: set[pl.Pauli]) -> int:
    basis = set(strings)
    frontier = list(basis)
    while frontier:
        new = []
        for a in frontier:
            for b in list(basis):
                if not pl.commutes(a, b):
                    r = pl.product(a, b)[1]
                    if r not in basis:
                        basis.add(r)
                        new.append(r)
        frontier = new
    return len(basis)


def _closure_dense(gens: list[Op], n: int, max_qubits: int = 6) -> int:
    if n > max_qubits:
        raise ValueError(f"dense closure limited to {max_qubits} qubits")
    dim_space = 4**n
    index = lambda p: p[0] * 2**n + p[1]

    def vec(g: Op) -> np.ndarray:
        v = np.zeros(dim_space)
        for p, c in g.items():
            v[index(p)] = c
        return v

    def op_of(v: np.ndarray) -> Op:
        nz = np.nonzero(np.abs(v) > 1e-10)[0]
        return {(int(i) // 2**n, int(i) % 2**n): float(v[i]) for i in nz}

    basis: list[np.ndarray] = []

    def add(v: np.ndarray) -> np.ndarray | None:
        for b in basis:
            v = v - (b @ v) * b
        nv = np.linalg.norm(v)
        if nv > 1e-8:
            u = v / nv
            basis.append(u)
            return u
        return None

    frontier = [u for g in gens if (u := add(vec(g))) is not None]
    while frontier:
        new = []
        for a in frontier:
            ao = op_of(a)
            for b in list(basis):
                c = _bracket(ao, op_of(b))
                if c and (u := add(vec(c))) is not None:
                    new.append(u)
        frontier = new
        if len(basis) == dim_space - 1:
            break
    return len(basis)


def lie_algebra_dimension(circuit: Circuit) -> int:
    gens = layer_generators(circuit)
    gens = [{p: v for p, v in g.items() if p != (0, 0)} for g in gens]  # identity part is a phase
    gens = [g for g in gens if g]
    if not gens:
        return 0
    if all(len(g) == 1 for g in gens):
        return _closure_strings({next(iter(g)) for g in gens})
    return _closure_dense(gens, circuit.n_qubits)
